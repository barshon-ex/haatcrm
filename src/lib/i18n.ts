const dicts: Record<Lang, Record<DictKey, string>> = { bn, en };

export type Dict = Record<DictKey, string>;

export function getDict(lang: Lang): Dict {
  return dicts[lang] ?? bn;
}

export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function num(n: number, lang: Lang): string {
  return n.toLocaleString(lang === "bn" ? "bn-BD" : "en-IN");
}

export function money(n: number, lang: Lang): string {
  return "৳" + num(n, lang);
}

export const STATUSES = ["pending", "confirmed", "packed", "shipped", "delivered", "returned", "cancelled"] as const;
export type OrderStatus = (typeof STATUSES)[number];

