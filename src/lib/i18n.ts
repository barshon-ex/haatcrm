/** SQLite stores UTC "YYYY-MM-DD HH:MM:SS"; show it in Bangladesh time. */
export function fmtDate(sqlUtc: string, lang: Lang, withTime = true): string {
  const d = new Date(sqlUtc.replace(" ", "T") + "Z");
  if (Number.isNaN(d.getTime())) return sqlUtc;
  return d.toLocaleString(lang === "bn" ? "bn-BD" : "en-GB", {
    timeZone: "Asia/Dhaka",
    day: "numeric",
    month: "short",
    year: "numeric",
    ...(withTime ? { hour: "numeric", minute: "2-digit" } : {}),
  });
}
